// Package reccatypes — то, что у всех дверей Recca ОДНО: конверт ответа,
// машинерия ошибок, деньги, календарная дата, страница списка.
//
// # Зачем пакет отделён от cpatypes
//
// У платформы две машинные поверхности — `/federation/v1/cpa/*` (CPA-сеть) и
// остальной `/federation/v1/*` (партнёрская федерация). Раму им даёт один и тот
// же `tenant-scope.ts`, конверт собирается по одному образцу, транспорт у них
// общий. Держать это в cpatypes значило бы, что клиент федерации возвращает
// `cpatypes.Response` — имя, которое врёт о предмете.
//
// # Чего здесь НЕТ и почему
//
// Здесь нет ни одного кода ошибки, принадлежащего конкретной двери, и ни одного
// типа предметной области. `PARTNER_NOT_FOUND` знает только CPA, `NOT_A_MEMBER`
// — только федерация; сложи их в общий словарь, и каждая поверхность начнёт
// обещать чужие отказы.
//
// Общими объявлены ровно те коды, которые ставит ОБЩАЯ рама: ключ, право,
// частота, внутренний сбой, негодный вход — плюс MALFORMED_RESPONSE, который
// ставит сам клиент. Это не соглашение об именах, а один и тот же код платформы
// (`api/middlewares/tenant-scope.ts`), и два сентинела на него значили бы, что
// `errors.Is` отвечает по-разному на один факт.
package reccatypes

// Ptr возвращает указатель на значение. Нужен там, где контракт различает «не
// передали» и «передали пустым»: без него три состояния поля выражались бы
// временной переменной на каждый вызов.
func Ptr[T any](v T) *T { return &v }
