package reccatypes

import "strconv"

// RUB — сумма в рублях, целым числом.
//
// ⚠⚠ Тип целый намеренно: float64 на деньгах даёт ошибку округления, которую не
// видно до сверки с кассой. Там, где дверь принимает дробную сумму, для неё
// заводится отдельный путь с ЛЕКСИЧЕСКОЙ формой числа — как его дал
// отправитель. Иначе 12.5 стало бы 12.50 и подпись перестала бы сходиться
// молча.
type RUB int64

// String — сумма без обозначения валюты: подставлять «₽» за потребителя значит
// решать за его интерфейс.
func (r RUB) String() string { return strconv.FormatInt(int64(r), 10) }
