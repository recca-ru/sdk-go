// Package version — версия модуля, объявленная ОДИН раз.
//
// ⚠⚠ Пакет заведён после выпуска v0.2.0, потому что разошлись ровно те два
// числа, которые обязаны быть одним. Модуль `go.recca.ru/sdk` один, версия у
// него одна, а констант было ДВЕ — `cpa.Version` и `federation.Version`, — и в
// выпущенном v0.2.0 первая рапортовала «0.1.0-dev», вторая «0.2.0-dev».
//
// Цена не косметическая. Строка уходит в User-Agent, и по ней в журналах Recca
// видно, какая версия клиента ходит — это единственный способ узнать это, не
// спрашивая интегратора. Выпущенный клиент, представляющийся сборкой
// разработчика, делает журнал бесполезным ровно для того вопроса, ради
// которого поле заведено; а клиент CPA внутри v0.2.0, называющийся 0.1.0,
// уводит разбор к прежнему модулю.
//
// ⚠ Приставку «-dev» несут только несобранные ветки между выпусками. Перед
// тегом её снимают, и это часть выпуска, а не украшение: тег ставится на
// дерево, которое уже называет себя своим номером.
package version

