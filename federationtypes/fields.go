package federationtypes

import (
	"errors"

	"go.recca.ru/sdk/reccatypes"
)

// ErrIncompleteData — в успешном ответе нет полного набора полей: data
// отсутствует, равен null, не содержит обязательного поля или прислал вместо
// него null.
//
// ⚠⚠ Отдельная ошибка, потому что «ноль» и «сервер не прислал данные» — разные
// ответы, и выдавать второй за первый значит показать потребителю выдуманные
// суммы: недостающие поля json.Unmarshal молча оставил бы нулями, и в
// интерфейсе появилось бы «баланс 0 ₽» вместо отказа.
//
// ⚠ Сентинел свой, а не общий с CPA: потребитель спрашивает errors.Is про ту
// дверь, в которую ходил, и текст отказа обязан называть именно её.
var ErrIncompleteData = errors.New("federation: в ответе нет полного набора данных")

// fields — как объявляет обязательность ЭТА поверхность. Сама проверка живёт в
// reccatypes и одна на обе двери: разойдись две копии рефлексии, и одна
// поверхность молча перестала бы требовать поля, оставаясь с виду строгой.
var fields = reccatypes.FieldSet{
	Surface:    "federation",
	Tag:        "federation",
	Incomplete: ErrIncompleteData,
}

// RequireFields отвечает, содержит ли data все обязательные поля типа T и ни
// одно из них не равно null. Имена берутся из json-тегов, обязательность — из
// тега `federation:"required"`, включая поля встроенных структур.
//
// Нулевые значения проверка пропускает: ноль — законный ответ. Посторонние поля
// рядом не мешают: новое поле в ответе — совместимая правка контракта.
func RequireFields[T any](data []byte) error {
	return reccatypes.RequireFields[T](fields, data)
}

// RequireFieldsEach — та же проверка для СТРАНИЦЫ: data обязана быть массивом, и
// полный набор полей обязана нести каждая её строка, а не первая.
func RequireFieldsEach[T any](data []byte) error {
	return reccatypes.RequireFieldsEach[T](fields, data)
}
