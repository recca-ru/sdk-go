// Package federationtypes — типы контракта федеративного API Recca:
// `/federation/v1/*`.
//
// Отдельный пакет от cpatypes намеренно, хотя машинерия у них общая
// (reccatypes). Это РАЗНЫЕ контракты разных дверей: у федерации свой конверт
// ответа, свой словарь кодов, свои правила идемпотентности, и сводить их в
// один пакет значило бы обещать потребителю единообразие, которого у дверей
// нет.
//
// ⚠⚠ Чем федеративная дверь отличается от CPA — три расхождения, каждое
// измерено по коду дверей 28.09.2026, и каждое видно в этих типах:
//
//  1. Конверт. CPA кладёт `request_id` в `meta` по контракту; общий
//     `successResponse` федерации — НИКОГДА, и на отказах блока `meta` нет
//     вовсе. Идентификатор при этом есть всегда, заголовком `X-Request-Id`, —
//     поэтому читать его надо из Response.RequestID, а не из Meta.
//
//  2. Признак следующей страницы. CPA пишет `has_more`, федерация — `hasMore`.
//     Обе формы живые; reccatypes.Meta принимает обе.
//
//  3. Идемпотентность. Заголовка `Idempotency-Key` федеративная дверь НЕ
//     читает — ни один роут `/federation/v1/*` его не спрашивает (проверено
//     грепом). Повтор различается по ТЕЛУ: `external_id` у конверсии и заявки,
//     пара «человек ⇆ оффер» у реферальной ссылки. Поэтому клиент такого
//     заголовка не шлёт: слать его значило бы обещать поведение, которого нет.
//
// ⚠ Денежные величины здесь float64, а не reccatypes.RUB. Дверь принимает и
// отдаёт произвольное конечное число (`typeof amount_rub !== "number"` —
// единственная её проверка), и целый тип отказал бы в сумме, которую живая
// дверь принимает. Лексическая форма, как у CPA-постбэка, здесь не нужна: на
// федеративных суммах не висит подписи, которая перестала бы сходиться от
// «12.5» против «12.50».
